ROOT = Path(__file__).resolve().parents[3]
EXAMPLES = ROOT / 'output/examples'


class Stub:
    name = 'test-stub'
    def __init__(self, analysis, context=None):
        self.analysis, self.reference_context = analysis, context or []
        self.called = 0
    def generate(self, messages):
        self.called += 1
        return json.dumps(self.analysis, ensure_ascii=False)


class KnowledgeTests(unittest.TestCase):
    def setUp(self):
        self.schema = load_schema(ROOT / 'output/study_material_analysis_schema_v0.2_draft.json')
        self.analysis = json.loads((EXAMPLES / '18_day_analysis_v0.2_draft.json').read_text(encoding='utf-8'))
        self.context = load_context(EXAMPLES / '18_day_reviewed_comments_v0.2.json', self.schema)
        self.data = from_collector(process_file(ROOT / 'test_file/18일차.txt'))

    def test_reviewed_comment_and_original_quotes(self):
        result, audit = analyze(self.data, Stub(self.analysis, self.context), self.schema)
        self.assertEqual(result['status'], 'SUCCESS')
        self.assertEqual(result['analysis'], self.analysis)
        self.assertFalse(audit['trace']['actual_ai_call'])
        self.assertEqual(audit['reference_context'], self.context)

    def test_no_comments_without_context(self):
        for section in self.analysis['sections']:
            section.pop('comment', None)
        self.analysis.pop('references')
        result, _ = analyze(self.data, Stub(self.analysis), self.schema)
        self.assertEqual(result['status'], 'SUCCESS')
        self.assertNotIn('references', result['analysis'])

    def test_model_cannot_self_certify(self):
        for mutate in [lambda a: None,
                       lambda a: a['sections'][-1]['comment'].update(text='근거 없이 새로 지어낸 설명이다.'),
                       lambda a: a['references'][0].update(checked_on='2026-10-16')]:
            data = copy.deepcopy(self.analysis)
            mutate(data)
            context = [] if data == self.analysis else self.context
            result, audit = analyze(self.data, Stub(data, context), self.schema)
            self.assertEqual(result['status'], 'SUCCESS')
            self.assertTrue(audit['auxiliary_review']['issues'])
            if data == self.analysis or data['sections'][-1]['comment']['text'] != self.analysis['sections'][-1]['comment']['text']:
                self.assertNotIn('comment', result['analysis']['sections'][-1])
                self.assertNotIn('references', result['analysis'])
            else:
                self.assertEqual(result['analysis']['references'], self.analysis['references'])

    def test_invalid_context_is_omitted_without_blocking_core(self):
        for change in [lambda c: c[0].update(verification_status='unverified'),
                       lambda c: c[0].update(checked_on='2026-02-30'),
                       lambda c: c.append(copy.deepcopy(c[0]))]:
            context = copy.deepcopy(self.context)
            change(context)
            provider = Stub(self.analysis, context)
            result, audit = analyze(self.data, provider, self.schema)
            self.assertEqual(result['status'], 'SUCCESS')
            self.assertNotIn('references', result['analysis'])
            self.assertEqual(audit['reference_context'], [])
            self.assertTrue(audit['auxiliary_review']['issues'])
            self.assertEqual(provider.called, 1)

    def test_section_links_coverage_and_single_comment(self):
        for mutate in [lambda a: a['sections'][0].update(content_refs=['/practice/999']),
                       lambda a: a['sections'][1].update(id=a['sections'][0]['id']),
                       lambda a: a['sections'].pop(0)]:
            data = copy.deepcopy(self.analysis)
            mutate(data)
            result, _ = analyze(self.data, Stub(data, self.context), self.schema)
            self.assertEqual(result['error']['code'], 'QUALITY_VALIDATION_ERROR')
        self.analysis['sections'][-1]['comment'] = [self.analysis['sections'][-1]['comment']] * 2
        self.assertTrue(schema_errors(self.analysis, self.schema))

    def test_api_schema_and_mock_roundtrip(self):
        # Supply the exact wire form: optional fields null, evidence line spans,
        # no source/reference metadata generated by the model.
        def fill(value, node):
            if '$ref' in node:
                node = self.schema['$defs'][node['$ref'].split('/')[-1]]
            if isinstance(value, dict):
                return {k: fill(value[k], child) if k in value else None
                        for k, child in node.get('properties', {}).items()
                        if k not in ('source', 'references')}
            if isinstance(value, list):
                return [fill(v, node['items']) for v in value]
            return value
        wire = fill(self.analysis, self.schema)
        wire['review_candidates'] = [{'section_id': 'vtp', 'kind': 'supplement',
                                     'text': 'VTP 동기화에는 domain과 password 외의 조건도 확인해야 한다.',
                                     'reason': '원문에 동기화 조건이 간략하게만 기록되어 있다.',
                                     'search_query': 'Cisco VTP configuration guidelines'}]
        def evidence(value):
            if isinstance(value, dict):
                for key, child in value.items():
                    if key == 'evidence':
                        text = self.data['extracted_text']
                        pos = text.index(child)
                        value[key] = {'start_line': text[:pos].count('\n') + 1,
                                      'end_line': text[:pos + len(child) - 1].count('\n') + 1}
                    else:
                        evidence(child)
            elif isinstance(value, list):
                for child in value:
                    evidence(child)
        evidence(wire)
        body = {'id': 'mock', 'status': 'completed', 'model': 'gpt-6-luna',
                'output': [{'type': 'message', 'content': [{'type': 'output_text', 'text': json.dumps(wire)}]}]}
        sent = []
        def transport(request, **kwargs):
            sent.append(json.loads(request.data))
            return Response(body)
        provider = OpenAIProvider(self.schema, api_key='test-key', transport=transport)
        provider.reference_context = self.context
        Draft202012Validator(provider.transport_schema).validate(wire)
        result, audit = analyze(self.data, provider, self.schema)
        self.assertEqual(result['status'], 'SUCCESS')
        self.assertEqual(result['analysis'], self.analysis)
        self.assertFalse(audit['trace']['actual_ai_call'])
        self.assertEqual(len(audit['review_request']['candidates']), 1)
        self.assertEqual(sent[0]['text']['format']['name'], 'study_analysis_v02')
        self.assertNotIn('references', provider.transport_schema['properties'])
        self.assertNotIn('test-key', json.dumps(audit))
        def check(node):
            if isinstance(node, dict):
                for key in ('allOf', 'if', 'then', 'const', 'uniqueItems'):
                    self.assertNotIn(key, node)
                if node.get('type') == 'object':
                    self.assertEqual(set(node['required']), set(node['properties']))
                for child in node.values():check(child)
            elif isinstance(node, list):
                for child in node:check(child)
        check(response_schema(self.schema))

    def test_cache_context_includes_reviewed_input(self):
        first = Stub(self.analysis, self.context)
        key1, _ = context_for(self.data, first, self.schema)
        context = copy.deepcopy(self.context)
        context[0]['comments'][0]['text'] = '다른 검토 설명이다.'
        key2, _ = context_for(self.data, Stub(self.analysis, context), self.schema)
        self.assertNotEqual(key1, key2)
        with tempfile.TemporaryDirectory() as directory:
            cache = Path(directory) / 'cache'
            result, _ = run_with_cache(self.data, first, self.schema, cache, directory)
            self.assertEqual(result['status'], 'SUCCESS')
            second = Stub(self.analysis, self.context)
            result, audit = run_with_cache(self.data, second, self.schema, cache, directory, reuse_only=True)
            self.assertEqual(result['status'], 'SUCCESS')
            self.assertTrue(audit['trace']['result_reused'])
            self.assertEqual(second.called, 0)
            result, _ = run_with_cache(self.data, Stub(self.analysis, context), self.schema,
                                       cache, directory, reuse_only=True)
            self.assertEqual(result['error']['code'], 'CACHE_MISS')

    def test_offline_recheck_with_review_context(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory)
            (path / 'analyzer_input.json').write_text(json.dumps(self.data), encoding='utf-8')
            (path / 'raw_response.json').write_text(json.dumps(self.analysis), encoding='utf-8')
            before = (path / 'raw_response.json').read_bytes()
            with patch('urllib.request.OpenerDirector.open', side_effect=AssertionError('no network')):
                _, result, audit = recheck_run(path, self.schema, self.context)
            self.assertEqual(result['status'], 'SUCCESS')
            self.assertFalse(audit['trace']['actual_ai_call'])
            self.assertEqual(before, (path / 'raw_response.json').read_bytes())
            _, result, audit = recheck_run(path, self.schema)
            self.assertEqual(result['status'], 'SUCCESS')
            self.assertNotIn('comment', result['analysis']['sections'][-1])
            self.assertTrue(audit['auxiliary_review']['issues'])
